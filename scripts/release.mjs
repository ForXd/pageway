import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gunzipSync } from 'node:zlib';

export const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const output = join(root, 'artifacts', 'npm');
export const packages = ['protocol', 'agent', 'react'];
export const repository = 'ForXd/pageway';
const registry = 'https://registry.npmjs.org';
const versionPattern =
  /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(?:-(?:[a-zA-Z0-9]+(?:[.-][a-zA-Z0-9]+)*))?$/;

export function run(command, args, cwd = root, capture = false) {
  // npm/pnpm are .cmd launchers on Windows. All arguments here are generated by
  // this script; double quotes protect temporary directory names containing spaces.
  const windows = process.platform === 'win32' && ['npm', 'pnpm'].includes(command);
  if (windows && args.some((arg) => /["\r\n%]/.test(arg)))
    throw new Error('Unsupported command argument.');
  return execFileSync(
    windows ? 'cmd.exe' : command,
    windows ? ['/d', '/s', '/c', `${command} ${args.map((arg) => `"${arg}"`).join(' ')}`] : args,
    {
      cwd,
      encoding: 'utf8',
      stdio: capture ? ['ignore', 'pipe', 'inherit'] : 'inherit',
      env: { ...process.env, npm_config_update_notifier: 'false' },
    },
  );
}

export async function manifests() {
  return Promise.all(
    packages.map(async (directory) => ({
      directory,
      ...JSON.parse(await readFile(join(root, 'packages', directory, 'package.json'), 'utf8')),
    })),
  );
}

export async function preflight(tag) {
  const entries = await manifests();
  const rootPackage = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));
  assert(
    versionPattern.test(rootPackage.version),
    'Use a fixed semantic version without build metadata.',
  );
  for (const entry of entries) {
    assert.equal(entry.name, `@zllling/pageway-${entry.directory}`);
    assert.equal(
      entry.version,
      rootPackage.version,
      `${entry.name}: all package versions must match the root version.`,
    );
    assert(!entry.private, `${entry.name} must be publishable.`);
    assert.equal(entry.license, 'MIT');
    assert.equal(entry.publishConfig?.access, 'public');
    assert.equal(entry.repository?.url, `git+https://github.com/${repository}.git`);
    assert.equal(entry.repository?.directory, `packages/${entry.directory}`);
    for (const [name, version] of Object.entries(entry.dependencies ?? {})) {
      if (name.startsWith('@zllling/pageway-'))
        assert.equal(
          version,
          'workspace:*',
          `${entry.name}: internal dependencies use workspace:*.`,
        );
    }
  }
  if (tag !== undefined) {
    assert.equal(
      tag,
      `v${rootPackage.version}`,
      'Release tag must exactly match the root and all package versions.',
    );
    assert.equal(
      run('git', ['rev-parse', `refs/tags/${tag}^{commit}`], root, true).trim(),
      run('git', ['rev-parse', 'HEAD'], root, true).trim(),
      'Check out the tagged commit before publishing.',
    );
  }
  console.log(
    `Release preflight passed: ${entries.map((entry) => `${entry.name}@${entry.version}`).join(', ')}`,
  );
  return entries;
}

/** Read regular files without extracting the archive or trusting its paths. */
export function tarFiles(bytes) {
  const tar = gunzipSync(bytes);
  const files = new Map();
  for (let offset = 0; offset + 512 <= tar.length;) {
    const header = tar.subarray(offset, offset + 512);
    if (header.every((byte) => byte === 0)) break;
    const field = (start, size) =>
      header
        .subarray(start, start + size)
        .toString('utf8')
        .replace(/\0.*$/, '');
    const name = [field(345, 155), field(0, 100)].filter(Boolean).join('/');
    const size = Number.parseInt(field(124, 12).trim() || '0', 8);
    assert(
      Number.isSafeInteger(size) && size >= 0 && offset + 512 + size <= tar.length,
      'Invalid package archive.',
    );
    if (header[156] === 0 || header[156] === 48) {
      assert(
        !name.split('/').includes('..') && name.startsWith('package/'),
        'Unsafe package archive path.',
      );
      assert(!files.has(name), `Duplicate archive entry: ${name}`);
      files.set(name, tar.subarray(offset + 512, offset + 512 + size));
    }
    offset += 512 + Math.ceil(size / 512) * 512;
  }
  return files;
}

export function inspectArchive(bytes, expected) {
  const files = tarFiles(bytes);
  const manifest = JSON.parse(files.get('package/package.json')?.toString('utf8') ?? '{}');
  assert.equal(manifest.name, expected.name);
  assert.equal(manifest.version, expected.version);
  assert.equal(manifest.license, 'MIT');
  assert.equal(manifest.repository?.url, `git+https://github.com/${repository}.git`);
  assert(
    files.has('package/dist/index.js') && files.has('package/dist/index.d.ts'),
    'Missing built JavaScript or declaration entry point.',
  );
  function checkExports(value) {
    if (typeof value === 'string') {
      assert(
        value.startsWith('./') && files.has(`package/${value.slice(2)}`),
        `Export target missing from tarball: ${value}`,
      );
      assert(
        !value.includes('/src/') || value.endsWith('.css'),
        'Published exports must not reference development TypeScript.',
      );
    } else {
      assert(value && typeof value === 'object', 'Invalid exports entry.');
      assert(
        !Object.hasOwn(value, 'development'),
        'Development condition must not escape into the published package.',
      );
      Object.values(value).forEach(checkExports);
    }
  }
  checkExports(manifest.exports);
  for (const [name, version] of Object.entries(manifest.dependencies ?? {})) {
    assert(
      !/^(?:workspace:|link:|file:)/.test(version),
      `Unresolved dependency: ${name}@${version}`,
    );
    if (name.startsWith('@zllling/pageway-'))
      assert.equal(
        version,
        expected.version,
        'Packed internal dependencies must use the fixed release version.',
      );
  }
  for (const path of files.keys())
    assert(
      !/(?:^|\/)(?:\.env(?:\.[^/]*)?|\.npmrc|node_modules)(?:\/|$)|\.(?:test|spec)\.[cm]?[jt]sx?$/.test(
        path,
      ),
      `Unexpected private or test file in package: ${path}`,
    );
  return {
    manifest,
    files,
    integrity: `sha512-${createHash('sha512').update(bytes).digest('base64')}`,
  };
}

export async function packPackages() {
  const entries = await preflight();
  run('pnpm', ['--filter', './packages/*', 'build']);
  await rm(output, { recursive: true, force: true });
  await mkdir(output, { recursive: true });
  const packed = [];
  for (const entry of entries) {
    run('pnpm', ['pack', '--pack-destination', output], join(root, 'packages', entry.directory));
    const filename = `${entry.name.replace('@', '').replace('/', '-')}-${entry.version}.tgz`;
    const { integrity } = inspectArchive(await readFile(join(output, filename)), entry);
    packed.push({ name: entry.name, version: entry.version, filename, integrity });
  }
  let commit = null;
  try {
    commit = execFileSync('git', ['rev-parse', 'HEAD'], {
      cwd: root,
      encoding: 'utf8',
      stdio: 'pipe',
    }).trim();
  } catch {
    /* An uncommitted local checkout can still be verified. */
  }
  await writeFile(
    join(output, 'manifest.json'),
    `${JSON.stringify({ commit, packages: packed }, null, 2)}\n`,
  );
  return packed;
}

async function readPacked() {
  const entries = await preflight();
  const artifactManifest = JSON.parse(await readFile(join(output, 'manifest.json'), 'utf8'));
  if (process.env.GITHUB_ACTIONS === 'true')
    assert.equal(
      artifactManifest.commit,
      run('git', ['rev-parse', 'HEAD'], root, true).trim(),
      'Artifacts must come from this exact release commit.',
    );
  const packed = artifactManifest.packages;
  assert(
    Array.isArray(packed) && packed.length === entries.length,
    'Expected exactly three package artifacts.',
  );
  for (let index = 0; index < entries.length; index++) {
    const entry = entries[index];
    const artifact = packed[index];
    const filename = `${entry.name.replace('@', '').replace('/', '-')}-${entry.version}.tgz`;
    assert.equal(artifact.name, entry.name);
    assert.equal(artifact.version, entry.version);
    assert.equal(artifact.filename, filename);
    assert.equal(
      inspectArchive(await readFile(join(output, filename)), entry).integrity,
      artifact.integrity,
      'Artifact integrity mismatch.',
    );
  }
  assert.deepEqual(
    (await readdir(output)).sort(),
    [...packed.map((entry) => entry.filename), 'manifest.json'].sort(),
    'Unexpected release artifacts.',
  );
  return packed;
}

export async function registryVersion(entry, fetchRegistry = fetch) {
  const response = await fetchRegistry(
    `${registry}/${encodeURIComponent(entry.name)}/${encodeURIComponent(entry.version)}`,
    {
      signal: AbortSignal.timeout(30_000),
      cache: 'no-store',
      headers: { Accept: 'application/json', 'Cache-Control': 'no-cache' },
    },
  );
  if (response.status === 404) return null;
  if (!response.ok)
    throw new Error(
      `Registry lookup failed for ${entry.name}: HTTP ${response.status}. Refusing to treat this as an unpublished version.`,
    );
  const published = await response.json();
  assert.equal(published.name, entry.name);
  assert.equal(published.version, entry.version);
  assert.equal(
    published.dist?.integrity,
    entry.integrity,
    `${entry.name}@${entry.version} is already published with different bytes. Bump all versions; never replace a release.`,
  );
  return published;
}

export async function waitForPublished(
  entry,
  {
    lookup = registryVersion,
    sleep = (milliseconds) => new Promise((resolveWait) => setTimeout(resolveWait, milliseconds)),
    now = Date.now,
    timeoutMs = 300_000,
  } = {},
) {
  const deadline = now() + timeoutMs;
  let attempt = 0;
  while (true) {
    // npm can acknowledge the upload while processing it asynchronously. Only
    // an integrity-checked registry response makes the dependency publishable.
    const published = await lookup(entry);
    if (published) return published;
    const remaining = deadline - now();
    assert(
      remaining > 0,
      `${entry.name} published but is not yet visible. Retry this workflow after registry propagation.`,
    );
    if (attempt++ % 6 === 0)
      console.log(
        `Waiting for ${entry.name}@${entry.version} to become visible in the registry...`,
      );
    await sleep(Math.min(5000, remaining));
  }
}

async function publish(tag) {
  assert.equal(
    process.env.GITHUB_ACTIONS,
    'true',
    'Automated publish runs only in GitHub Actions. Use the documented bootstrap procedure for first publication.',
  );
  assert.equal(process.env.GITHUB_REPOSITORY, repository, 'Unexpected publishing repository.');
  assert(
    process.env.ACTIONS_ID_TOKEN_REQUEST_URL && process.env.ACTIONS_ID_TOKEN_REQUEST_TOKEN,
    'GitHub OIDC is unavailable. The publish job requires id-token: write.',
  );
  assert(
    !process.env.NODE_AUTH_TOKEN && !process.env.NPM_TOKEN,
    'Do not mix long-lived npm tokens with trusted publishing.',
  );
  await preflight(tag);
  const packed = await readPacked();
  const existing = await Promise.all(packed.map((entry) => registryVersion(entry)));
  for (let index = 0; index < packed.length; index++) {
    const entry = packed[index];
    if (existing[index]) {
      console.log(`Already published with identical integrity: ${entry.name}@${entry.version}`);
      continue;
    }
    run('npm', [
      'publish',
      join(output, entry.filename),
      '--access',
      'public',
      '--provenance',
      '--tag',
      entry.version.includes('-') ? 'next' : 'latest',
      '--registry',
      registry,
      '--ignore-scripts',
    ]);
    await waitForPublished(entry);
  }
}

async function main() {
  const [command = 'preflight', ...args] = process.argv.slice(2);
  assert(
    args.length === 0 || (args.length === 2 && args[0] === '--tag'),
    'Usage: node scripts/release.mjs <preflight|dry-run|publish> [--tag v0.1.0]',
  );
  const tag = args[1];
  if (command === 'preflight') await preflight(tag);
  else if (command === 'dry-run') {
    const { verifyPacked } = await import('./verify-packed.mjs');
    await verifyPacked();
    for (const entry of await readPacked())
      run('npm', [
        'publish',
        join(output, entry.filename),
        '--dry-run',
        '--access',
        'public',
        '--ignore-scripts',
        '--registry',
        registry,
      ]);
    console.log('Dry run complete. No package was uploaded.');
  } else if (command === 'publish') {
    assert(tag, 'Publishing requires --tag.');
    await publish(tag);
  } else throw new Error(`Unknown release command: ${command}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
