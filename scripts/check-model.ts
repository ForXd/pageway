import { existsSync } from 'node:fs';
import { randomUUID } from 'node:crypto';
import { fileURLToPath } from 'node:url';

// Run from any directory. Explicit environment variables take precedence over .env.
const envPath = fileURLToPath(new URL('../.env', import.meta.url));
if (existsSync(envPath)) process.loadEnvFile(envPath);

const model = process.env.MODEL_NAME || 'nvidia/nemotron-3.5-lightning:free';
const baseURL = process.env.MODEL_BASE_URL || 'https://ai-gateway.kilo.ai/api/v1';
const apiKey = process.env.MODEL_API_KEY?.trim();
const token = 'PAGEWAY_OK';
const timeoutMs = Number(process.env.AGENT_TIMEOUT_MS || 180_000);
if (!Number.isFinite(timeoutMs) || timeoutMs < 1 || timeoutMs > 300_000)
  throw new Error('AGENT_TIMEOUT_MS must be between 1 and 300000.');

type JsonObject = Record<string, unknown>;
type Message = JsonObject & { role: string };

function object(value: unknown): value is JsonObject {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function safeMessage(message: string): string {
  const redacted = apiKey ? message.replaceAll(apiKey, '[redacted]') : message;
  return redacted.replace(/[\r\n\t]+/g, ' ').slice(0, 600);
}

async function completion(messages: Message[], extra: JsonObject = {}): Promise<JsonObject> {
  const endpoint = new URL(`${baseURL.replace(/\/+$/, '')}/chat/completions`);
  if (!['http:', 'https:'].includes(endpoint.protocol) || endpoint.username || endpoint.password) {
    throw new Error('MODEL_BASE_URL must be an HTTP(S) URL without embedded credentials.');
  }
  const headers: Record<string, string> = { 'Content-Type': 'application/json' };
  if (apiKey) headers.Authorization = `Bearer ${apiKey}`;

  const response = await fetch(endpoint, {
    method: 'POST',
    headers,
    body: JSON.stringify({ model, messages, stream: false, ...extra }),
    signal: AbortSignal.timeout(timeoutMs),
  });
  const raw = await response.text();
  let payload: unknown;
  try {
    payload = JSON.parse(raw);
  } catch {
    throw new Error(`HTTP ${response.status}: provider returned non-JSON data.`);
  }
  if (!response.ok) {
    const error = object(payload) && object(payload.error) ? payload.error : undefined;
    const detail =
      error && typeof error.message === 'string'
        ? safeMessage(error.message)
        : 'Provider rejected the request.';
    throw new Error(`HTTP ${response.status}: ${detail}`);
  }
  const choices = object(payload) && Array.isArray(payload.choices) ? payload.choices : [];
  const choice: unknown = choices[0];
  if (!object(choice) || !object(choice.message)) {
    throw new Error('Expected choices[0].message in an OpenAI Chat Completions response.');
  }
  if (object(payload) && typeof payload.model === 'string')
    console.log(`Response model: ${safeMessage(payload.model)}`);
  return choice.message;
}

const tools = [
  {
    type: 'function',
    function: {
      name: 'pageway_echo',
      description: 'Returns the supplied test message. This tool has no side effects.',
      parameters: {
        type: 'object',
        properties: { message: { type: 'string', enum: [token] } },
        required: ['message'],
        additionalProperties: false,
      },
    },
  },
];

async function main(): Promise<void> {
  console.log(
    `Checking ${safeMessage(model)} with ${apiKey ? 'configured' : 'no'} API key (never printed).`,
  );
  console.log(
    `Only synthetic test messages are sent. Each request has a ${timeoutMs / 1000}-second timeout.`,
  );

  const text = await completion([{ role: 'user', content: `Reply with exactly ${token}.` }]);
  if (typeof text.content !== 'string' || !text.content.includes(token)) {
    throw new Error('Text completion returned no expected test token.');
  }
  console.log('PASS: text completion');

  const messages: Message[] = [
    {
      role: 'user',
      content: `Call pageway_echo with message ${token}. After the tool returns, reply with its message and its exact receipt. The receipt is generated by the tool, so wait for the result.`,
    },
  ];
  const assistant = await completion(messages, { tools, tool_choice: 'required' });
  const calls = Array.isArray(assistant.tool_calls) ? assistant.tool_calls : [];
  if (calls.length !== 1 || !object(calls[0])) {
    throw new Error(
      'Expected exactly one structured tool call; prose about calling a tool is not sufficient.',
    );
  }
  const call = calls[0];
  if (
    typeof call.id !== 'string' ||
    call.type !== 'function' ||
    !object(call.function) ||
    call.function.name !== 'pageway_echo' ||
    typeof call.function.arguments !== 'string'
  ) {
    throw new Error('Provider returned an invalid OpenAI function tool call.');
  }
  let args: unknown;
  try {
    args = JSON.parse(call.function.arguments);
  } catch {
    throw new Error('Tool call arguments are not valid JSON.');
  }
  if (!object(args) || args.message !== token) {
    throw new Error('Tool call did not pass the expected synthetic argument.');
  }
  console.log('PASS: structured function call and JSON arguments');

  // Preserve provider-specific assistant fields, e.g. reasoning_content, in continuation.
  messages.push({ ...assistant, role: 'assistant' });
  const receipt = `PAGEWAY-${randomUUID()}`;
  messages.push({
    role: 'tool',
    tool_call_id: call.id,
    content: JSON.stringify({ message: token, receipt }),
  });
  const final = await completion(messages, { tools, tool_choice: 'none' });
  if (
    typeof final.content !== 'string' ||
    !final.content.includes(token) ||
    !final.content.includes(receipt) ||
    (Array.isArray(final.tool_calls) && final.tool_calls.length > 0)
  ) {
    throw new Error('Tool-result continuation did not return the expected final text.');
  }
  console.log('PASS: tool-result continuation with a fresh tool-only receipt');
  console.log('Model supports the text → tool call → tool result → final reply cycle.');
}

try {
  await main();
} catch (error) {
  const message = error instanceof Error ? error.message : 'Unknown provider error.';
  console.error(`FAIL: ${safeMessage(message)}`);
  console.error(
    'No model success is assumed. See docs/providers.md for setup and known provider restrictions.',
  );
  process.exitCode = 1;
}
